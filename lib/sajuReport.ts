const avgToLevel = (values: number[]): Level => {
  if (values.length === 0) return "MID" // 활성 관계 없음 → 중립
  const avg = values.reduce((a, b) => a + b, 0) / values.length
  return avg >= 1.5 ? "HIGH" : avg >= 0.5 ? "MID" : "LOW"
}

