export function buildSajuReport(x: SajuComputed): SajuReport {
  // ── 섹션1: 연애 기질 ──
  const s = {
    식신: toScore(x.식신_개수),
    상관: toScore(x.상관_개수),
    인성: toScore(x.인성_개수),
    비겁: toScore(x.비겁_개수),
    관성: toScore(x.관성_개수),
    재성: toScore(x.재성_개수),
  }
  const 식상점수 = (s.식신 + s.상관) / 2
  const raw표현 = Math.floor(s.식신 * 0.4 + s.상관 * 0.4 - s.인성 * 0.2 + 50)
  const raw감정 = Math.floor(x.수오행_점수 * 0.5 + s.인성 * 0.3 + x.음간보정 * 0.2 + 30)
  const raw주도 = Math.floor(s.비겁 * 0.5 + s.관성 * 0.2 + 식상점수 * 0.1 + 30)
  const raw집착 = Math.floor(s.관성 * 0.4 + x.수오행_점수 * 0.3 + s.인성 * 0.2 + 20)

  const off = STEM_OFFSET[x.일간] ?? { 표현: 0, 주도: 0 }
  const eaOff = x.음양 === "양간" ? 10 : -10 // 감정깊이·집착도 오프셋

  const 표현최종 = clamp(raw표현 + off.표현)
  const 감정최종 = clamp(raw감정 + eaOff)
  const 주도최종 = clamp(raw주도 + off.주도)
  const 집착최종 = clamp(raw집착 + eaOff)

  const t표현 = pickTag(TABLE_표현, 표현최종)
  const t감정 = pickTag(TABLE_감정, 감정최종)
  const t주도 = pickTag(TABLE_주도, 주도최종)
  const t집착 = pickTag(TABLE_집착, 집착최종)

  // ── 섹션2: 이상형 유형 ──
  const 강도 = 관성강도(x.관성_개수)
  const attract = ATTRACT[`${x.음양}|${강도}`]
  const 중이상 = 강도 === "중" || 강도 === "강"
  const avoid = AVOID[`${x.음양}|${중이상 ? "중이상" : "없음약"}`]

  // ── 섹션3: 올해 연애운 ──
  const active = RELATION_LEVELS.filter(r => x[r.key] === true)
  const levels: Level[] = [0, 1, 2].map(i => avgToLevel(active.map(r => r.v[i]))) as Level[]
  const 기간 = ["1–6월", "7–9월", "10–12월"] as const

  // ── 섹션4: 주의 포인트 (상위 2개) ──
  const triggered = CATALOG.filter(c => c.trigger(x)).sort(
    (a, b) => b.score - a.score || a.id.localeCompare(b.id),
  )
  let cautions: CautionEntry[]
  if (triggered.length === 0) {
    cautions = [entry("C02"), entry("C04")]
  } else if (triggered.length === 1) {
    const partner = triggered[0].id === "C04" ? entry("C02") : entry("C04")
    cautions = [triggered[0], partner]
  } else {
    cautions = triggered.slice(0, 2)
  }

  return {
    meta: {
      시주입력여부: x.시주_입력여부,
      ...(x.시주_입력여부 ? {} : { 시주미입력안내: "시간 미입력으로 일부 수치가 부정확할 수 있어요." }),
    },
    섹션1_연애기질: {
      ai_tags: { express: 표현최종, emotion: 감정최종, lead: 주도최종, attach: 집착최종 },
      표현방식: { 원점수: raw표현, 최종점수: 표현최종, 태그: t표현.태그, 설명: t표현.설명 },
      감정깊이: { 원점수: raw감정, 최종점수: 감정최종, 태그: t감정.태그, 설명: t감정.설명 },
      주도성: { 원점수: raw주도, 최종점수: 주도최종, 태그: t주도.태그, 설명: t주도.설명 },
      집착도: { 원점수: raw집착, 최종점수: 집착최종, 태그: t집착.태그, 설명: t집착.설명 },
    },
    섹션2_이상형유형: {
      끌리는유형: { ...attract },
      피하면좋은유형: { ...avoid },
    },
    섹션3_올해연애운: {
      상반기: { 기간: 기간[0], 레벨: levels[0], 텍스트: PERIOD_TEXT[levels[0]][0] },
      하반기: { 기간: 기간[1], 레벨: levels[1], 텍스트: PERIOD_TEXT[levels[1]][1] },
      연말: { 기간: 기간[2], 레벨: levels[2], 텍스트: PERIOD_TEXT[levels[2]][2] },
    },
    섹션4_주의포인트: cautions.map(strip),
  }
}
